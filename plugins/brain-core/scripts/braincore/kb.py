"""`brain kb`: build and query the knowledge-base index. Contract: system/schema/_schema.md (v3).

    brain kb build [--force] [--check] [--as-brick NAME]
    brain kb index [--as-brick NAME]
    brain kb query "select count(*) from entries"
    brain kb show <id>
    brain kb attention [--today YYYY-MM-DD] [--as-brick NAME]
    brain kb trust <project-slug> [--raw <raw-id>]
    brain kb append --project <slug> --file <payload.json> [--dry-run] [--no-auto-confirm]
    brain kb propose --title "..." --source <id> [--audience system|owner] [--body "..."]
    brain kb confirm <DEC-id | project/ID | PRP-NNN> [--reject]

Markdown is the source of truth; system/kb.db is generated. `build` validates everything first
and writes nothing on any error. Every path comes from .claude/paths.json (section "core").
Output is JSON (one object per line for `query`). `--as-brick` wraps the result in a brick
contract return so the orchestrator can run the command as a script step.
"""
