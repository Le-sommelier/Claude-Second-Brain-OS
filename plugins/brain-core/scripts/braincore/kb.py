def _yaml():
    try:
        import yaml  # PyYAML: frontmatter here carries nested maps (attendance, members)
    except ImportError as exc:  # pragma: no cover
        raise SystemExit("brain kb needs PyYAML: python3 -m pip install pyyaml") from exc
    return yaml


def kbpath(key: str) -> Path:
    return path("core", key)


def schema_file(name: str) -> Path:
    """Workspace copy first (the owner may customise attention.yaml), plugin copy as fallback."""
    p = kbpath("schema") / name
    return p if p.is_file() else PLUGIN_SCHEMA / name


def owner_id() -> str:
    return str(owner().get("person_id") or "owner")


def owner_label() -> str:
    return str(owner().get("first_name") or "the owner")


# ---------------------------------------------------------------- grammar

FACETS = {"status": "STA", "risks": ("RSK", "DEP"), "resources": "RES", "milestones": "MS", "hypotheses": "HYP"}
LOG_FACETS = set(FACETS)  # teams.md is YAML frontmatter, not an entry log
STATES = {"open", "closed", "mitigated", "proposed", "accepted", "superseded", "at-risk", "on-track",
          "off-track", "done", "slipped"}
BY = {"human", "ai", "ai-confirmed"}
TRUST = {"high", "medium", "low"}
DEC_STATUS = {"proposed", "accepted", "superseded", "rejected"}
RAW_KINDS = {"meetings": "mtg", "slack": "slack", "confluence": "conf", "notes": "note", "sources": "src"}
ATTENDANCE = {"attended", "invited-absent", "not-invited"}
TRUST_RANK = {"high": 3, "medium": 2, "low": 1}

HEADER_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2}) · ((?:RSK|DEP|MS|STA|RES|HYP)-\d{3}) · ([a-z-]+)\s*$")
FENCE_RE = re.compile(r"<!-- human -->.*?<!-- /human -->", re.DOTALL)
LINK_RE = re.compile(r"\[\[([A-Za-z0-9_./-]+?)(?:\|[^\]]*)?\]\]")
FM_RE = re.compile(r"\A---[ \t]*\n(.*?)\n---[ \t]*(?:\n|\Z)", re.DOTALL)
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
RAW_ID_RE = re.compile(r"^(mtg|slack|conf|note|src)-(\d{4}-\d{2}-\d{2})-[a-z0-9-]+$")

GEN_START, GEN_END = "<!-- generated -->", "<!-- /generated -->"
INDEX_MARK = "<!-- generated by kb index; do not edit -->"
SKIP_DIRS = {"node_modules", "__pycache__", ".venv", "scripts", "references", "tests", "assets", "artefacts"}
INDEX_SKIP_SYSTEM = {"run", "sessions"}  # machine state, not browsable


class BuildError(Exception):
    pass


def split_fm(text: str) -> tuple[dict, str]:
    m = FM_RE.match(text)
    if not m:
        return {}, text
    try:
        fm = _yaml().safe_load(m.group(1)) or {}
    except _yaml().YAMLError as exc:
        raise BuildError(f"bad frontmatter: {exc}") from exc
    return (fm if isinstance(fm, dict) else {}), text[m.end():]


def blank_fences(text: str) -> str:
    """Replace human-fenced regions by same-length blank lines so line numbers stay valid."""
    return FENCE_RE.sub(lambda m: "\n" * m.group(0).count("\n"), text)


def parse_entries(p: Path, project: str, facet: str, errors: list[str]) -> list[dict]:
    lines = blank_fences(p.read_text(encoding="utf-8")).splitlines()
    out: list[dict] = []
    i = 0
    while i < len(lines):
        m = HEADER_RE.match(lines[i])
        if not m:
            if re.match(r"^## \d{4}-", lines[i]):
                errors.append(f"{rel(p)}:{i + 1}: malformed entry header: {lines[i]!r}")
            i += 1
            continue
        d, eid, state = m.groups()
        line_no = i + 1
        where = f"{rel(p)}:{line_no}"
        meta: dict[str, str] = {}
        j = i + 1
        if j < len(lines) and lines[j].startswith("by: "):
            for part in lines[j].split(" · "):
                k, _, v = part.partition(": ")
                meta[k.strip()] = v.strip()
        else:
            errors.append(f"{where}: {eid} missing 'by:' metadata line")
        j += 1
        body_lines = []
        while j < len(lines) and not lines[j].startswith("## "):
            body_lines.append(lines[j])
            j += 1
        i = j
        expected = FACETS.get(facet)
        prefixes = (expected,) if isinstance(expected, str) else expected
        if not any(eid.startswith(px + "-") for px in prefixes):
            errors.append(f"{where}: ID {eid} not allowed in {facet}.md (expected {'/'.join(prefixes)})")
        if state not in STATES:
            errors.append(f"{where}: unknown state {state!r}")
        by = meta.get("by")
        if by not in BY:
            errors.append(f"{where}: by must be one of {sorted(BY)}, got {by!r}")
        if by and by != "human" and meta.get("trust") not in TRUST:
            errors.append(f"{where}: trust required (high|medium|low) when by={by}")
        if not meta.get("source"):
            errors.append(f"{where}: source is mandatory")
        if meta.get("due") and not DATE_RE.match(meta["due"]):
            errors.append(f"{where}: bad due date {meta['due']!r}")
        out.append({"key": f"{project}/{eid}", "project": project, "facet": facet, "id": eid, "date": d,
                    "state": state, "by": by, "trust": meta.get("trust"), "source": meta.get("source"),
                    "owner": meta.get("owner"), "due": meta.get("due"), "rag": meta.get("rag"),
                    "body": "\n".join(body_lines).strip(), "path": rel(p), "line": line_no})
    return out


def validate_file(p: Path) -> list[str]:
    """Grammar errors for one facet log (used by the PostToolUse hook). Empty when clean."""
    facet = p.stem
    if facet not in LOG_FACETS:
        return []
    errors: list[str] = []
    parse_entries(p, p.parent.name, facet, errors)
    return errors


# ---------------------------------------------------------------- collection


def md_files(base: Path) -> list[Path]:
    if not base.is_dir():
        return []
    return sorted(p for p in base.rglob("*.md")
                  if not any(x.startswith(".") or x in SKIP_DIRS for x in p.relative_to(base).parts[:-1]))


def title_of(p: Path, fm: dict, body: str) -> str:
    if fm.get("title"):
        return str(fm["title"])
    m = re.search(r"^# (.+)$", body, re.MULTILINE)
    return m.group(1).strip() if m else p.stem


def collect() -> tuple[dict, list[str], list[str], str]:
    """Parse every source file. Returns (rows, errors, warnings, source_hash)."""
    yaml = _yaml()
    errors: list[str] = []
    warnings: list[str] = []
    rows: dict[str, list] = {k: [] for k in (
        "entities", "raw_items", "people", "project_members", "meeting_attendees", "entries",
        "decisions", "links", "sessions", "proposals", "fts")}
    h = hashlib.sha256()
    me = owner_id()

    def read(p: Path) -> str:
        data = p.read_bytes()
        h.update(rel(p).encode() + b"\0" + hashlib.sha256(data).digest())
        return data.decode("utf-8")

    def add_links(src: str, text: str, p: Path) -> None:
        for n, line in enumerate(text.splitlines(), 1):
            for m in LINK_RE.finditer(line):
                rows["links"].append((src, m.group(1), "cite", rel(p), n))

    # people (org chart owned by the stakeholders module + owner)
    org = kbpath("org")
    person_ids: set[str] = set()
    if org.is_file():
        try:
            data = yaml.safe_load(read(org)) or {}
        except yaml.YAMLError as exc:
            errors.append(f"{rel(org)}: {exc}")
            data = {}
        for pr in data.get("people", []) or []:
            pid = pr.get("id") if isinstance(pr, dict) else None
            if not pid or not pr.get("name"):
                errors.append(f"{rel(org)}: person needs id and name: {pr!r}")
                continue
            person_ids.add(pid)
            page = kbpath("people") / f"{pid}.md"
            rows["people"].append((pid, pr["name"], pr.get("role"), pr.get("tier"), pr.get("manager"),
                                   pr.get("email"), pr.get("slack_id"), rel(page) if page.is_file() else None))
    else:
        warnings.append(f"{rel(org)} missing: trust tiers fall back to the owner only")

    def entity_page(p: Path, etype: str, eid: str) -> None:
        fm, body = split_fm(read(p))
        rows["entities"].append((eid, etype, title_of(p, fm, body), rel(p), fm.get("owner"),
                                 fm.get("status"), str(fm.get("updated") or fm.get("last_reviewed") or "") or None))
        rows["fts"].append((eid, etype, rel(p), title_of(p, fm, body), body))
        add_links(eid, body, p)

    # projects and topics
    for domain, etype, prefix in (("projects", "project", "proj-"), ("topics", "topic", "topic-")):
        base = kbpath(domain)
        if not base.is_dir():
            continue
        for d in sorted(x for x in base.iterdir() if x.is_dir() and not x.name.startswith((".", "_"))):
            slug = d.name
            eid = prefix + slug
            readme = d / "README.md"
            if readme.is_file():
                try:
                    entity_page(readme, etype, eid)
                except BuildError as exc:
                    errors.append(f"{rel(readme)}: {exc}")
            else:
                rows["entities"].append((eid, etype, slug, rel(d), None, None, None))
            for facet in sorted(LOG_FACETS):
                f = d / f"{facet}.md"
                if f.is_file():
                    text = read(f)
                    add_links(f"{slug}/{facet}", text, f)
                    for e in parse_entries(f, slug, facet, errors):
                        rows["entries"].append(e)
                        rows["fts"].append((e["key"], "entry", e["path"], e["id"], e["body"]))
            skip_pages = {"README.md", "teams.md", *(f"{f}.md" for f in LOG_FACETS)}
            for pg in md_files(d):
                parts = pg.relative_to(d).parts
                if parts[0] in ("decisions", "rollups") or (pg.name in skip_pages and len(parts) == 1) \
                        or pg.name.startswith("_"):
                    continue
                try:
                    pfm, pbody = split_fm(read(pg))
                except BuildError as exc:
                    errors.append(f"{rel(pg)}: {exc}")
                    continue
                rows["fts"].append((f"{eid}:{'/'.join(parts)}", "page", rel(pg), title_of(pg, pfm, pbody), pbody))
            teams = d / "teams.md"
            if teams.is_file():
                try:
                    fm, _ = split_fm(read(teams))
                except BuildError as exc:
                    errors.append(f"{rel(teams)}: {exc}")
                    fm = {}
                for mem in fm.get("members", []) or []:
                    pid = mem.get("person")
                    if org.is_file() and pid not in person_ids:
                        warnings.append(f"{rel(teams)}: member {pid!r} not in the org chart")
                    rows["project_members"].append((eid, pid, mem.get("role"), int(bool(mem.get("owner"))),
                                                    int(bool(mem.get("decision_maker")))))
            for dec in md_files(d / "decisions"):
                if dec.name.startswith("_"):
                    continue
                try:
                    fm, body = split_fm(read(dec))
                except BuildError as exc:
                    errors.append(f"{rel(dec)}: {exc}")
                    continue
                did = fm.get("id")
                if not did:
                    errors.append(f"{rel(dec)}: decision frontmatter needs id")
                    continue
                if fm.get("status") not in DEC_STATUS:
                    errors.append(f"{rel(dec)}: status must be one of {sorted(DEC_STATUS)}")
                if fm.get("by") not in BY:
                    errors.append(f"{rel(dec)}: by must be one of {sorted(BY)}")
                if fm.get("by") != "human" and fm.get("trust") not in TRUST:
                    errors.append(f"{rel(dec)}: trust required when by != human")
                if not fm.get("source"):
                    errors.append(f"{rel(dec)}: source is mandatory")
                rows["decisions"].append((did, slug, str(fm.get("date", "")), title_of(dec, fm, body), fm.get("status"),
                                          fm.get("by"), fm.get("trust"), fm.get("source"), fm.get("owner"),
                                          fm.get("supersedes"), rel(dec)))
                rows["fts"].append((did, "decision", rel(dec), title_of(dec, fm, body), body))
                add_links(did, body, dec)

    # person pages -> fts/links
    for p in md_files(kbpath("people")):
        if p.name.startswith("_"):
            continue
        try:
            fm, body = split_fm(read(p))
        except BuildError as exc:
            errors.append(f"{rel(p)}: {exc}")
            continue
        rows["fts"].append((p.stem, "person", rel(p), title_of(p, fm, body), body))
        add_links(p.stem, body, p)

    # raw items: raw/<kind>/YYYY/YYYY-Www/<id>{.txt,.md,.summary.md,.meta.yaml}
    raw = kbpath("raw")
    seen: dict[str, dict] = {}
    if raw.is_dir():
        for p in sorted(x for x in raw.rglob("*") if x.is_file() and not x.name.startswith((".", "_"))
                        and x.name != "CLAUDE.md"):
            parts = p.relative_to(raw).parts
            if len(parts) < 4 or parts[0] not in RAW_KINDS or any(x.startswith((".", "_")) for x in parts[:-1]):
                continue
            m = re.match(r"^(.*?)(\.summary\.md|\.meta\.yaml|\.txt|\.md)$", p.name)
            if not m:
                continue
            rid, suffix = m.groups()
            if not RAW_ID_RE.match(rid):
                errors.append(f"{rel(p)}: raw filename is not <kind>-YYYY-MM-DD-<slug>")
                continue
            kind = rid.split("-", 1)[0]
            if RAW_KINDS[parts[0]] != kind:
                errors.append(f"{rel(p)}: id kind {kind!r} does not match folder {parts[0]!r}")
            rec = seen.setdefault(rid, {"kind": kind, "paths": {}, "fm": {}, "text": ""})
            rec["paths"][suffix] = p
            if suffix in (".summary.md", ".md"):
                try:
                    fm, body = split_fm(read(p))
                except BuildError as exc:
                    errors.append(f"{rel(p)}: {exc}")
                    continue
                rec["fm"].update(fm)
                if suffix == ".summary.md" or not rec["text"]:
                    rec["text"] = body
                add_links(rid, body, p)
            elif suffix == ".meta.yaml":
                try:
                    rec["fm"].setdefault("_sidecar", yaml.safe_load(read(p)) or {})
                except yaml.YAMLError as exc:
                    errors.append(f"{rel(p)}: {exc}")
            else:
                read(p)  # hash raw content so edits are detected (never written)
    for rid, rec in sorted(seen.items()):
        fm = {**rec["fm"].get("_sidecar", {}), **{k: v for k, v in rec["fm"].items() if k != "_sidecar"}}
        dstr = RAW_ID_RE.match(rid).group(2)
        main = rec["paths"].get(".txt") or rec["paths"].get(".md") or rec["paths"].get(".summary.md") \
            or next(iter(rec["paths"].values()))
        att = fm.get("attendance")
        if isinstance(att, dict):
            for pid, a in sorted(att.items()):
                if a not in ATTENDANCE:
                    errors.append(f"{rel(main)}: attendance {a!r} for {pid} invalid")
                if org.is_file() and pid not in person_ids:
                    warnings.append(f"{rel(main)}: attendee {pid!r} not in the org chart")
                rows["meeting_attendees"].append((rid, pid, a))
            att_self = att.get(me)
        else:
            att_self = att
        if att_self is not None and att_self not in ATTENDANCE:
            errors.append(f"{rel(main)}: attendance {att_self!r} invalid")
            att_self = None
        iso = date.fromisoformat(dstr).isocalendar()
        redact = bool(fm.get("redact_content")) or str(fm.get("sensitivity", "")).lower() == "confidential"
        rows["raw_items"].append((rid, rec["kind"], dstr, f"{iso.year}-W{iso.week:02d}", str(fm.get("title") or rid),
                                  rel(main), rel(rec["paths"][".summary.md"]) if ".summary.md" in rec["paths"] else None,
                                  att_self, fm.get("project"), fm.get("meeting_type"),
                                  int(bool(fm.get("wiki_processed"))), int(redact)))
        if rec["text"]:
            rows["fts"].append((rid, rec["kind"], rel(main), str(fm.get("title") or rid), rec["text"]))

    # adrs, proposals, sessions, code repos
    for p in md_files(kbpath("adrs")):
        if p.name.startswith("_"):
            continue
        m = re.match(r"(ADR-\d+)", p.stem)
        try:
            entity_page(p, "adr", m.group(1) if m else p.stem)
        except BuildError as exc:
            errors.append(f"{rel(p)}: {exc}")
    for p in md_files(kbpath("proposals")):
        if p.name.startswith("_"):
            continue
        try:
            fm, body = split_fm(read(p))
        except BuildError as exc:
            errors.append(f"{rel(p)}: {exc}")
            continue
        if not fm.get("id"):
            errors.append(f"{rel(p)}: proposal needs id")
            continue
        if fm.get("audience") not in (None, "system", "owner"):
            errors.append(f"{rel(p)}: audience must be system or owner")
            continue
        rows["proposals"].append((fm["id"], fm.get("audience"), str(fm.get("date", "")), fm.get("state", "open"),
                                  fm.get("title"), fm.get("source"), rel(p)))
        rows["fts"].append((fm["id"], "proposal", rel(p), fm.get("title") or fm["id"], body))
    sdir = kbpath("sessions")
    if sdir.is_dir():
        for p in sorted(sdir.rglob("*.jsonl")):
            for n, line in enumerate(read(p).splitlines(), 1):
                if not line.strip():
                    continue
                try:
                    r = json.loads(line)
                except json.JSONDecodeError as exc:
                    errors.append(f"{rel(p)}:{n}: {exc}")
                    continue
                if not r.get("id") or not r.get("date"):
                    warnings.append(f"{rel(p)}:{n}: session record needs id and date")
                    continue
                rows["sessions"].append((r.get("id"), r.get("date"), r.get("model"), r.get("summary"),
                                         json.dumps(r.get("files_touched", [])), rel(p)))
    code = kbpath("code")
    if code.is_dir():
        for d in sorted(x for x in code.iterdir() if x.is_dir() and (x / "README.md").is_file()):
            try:
                entity_page(d / "README.md", "repo", f"repo-{d.name}")
            except BuildError as exc:
                errors.append(f"{rel(d / 'README.md')}: {exc}")
    return rows, errors, warnings, h.hexdigest()


# ---------------------------------------------------------------- brick wrapper


def brick_return(name: str, status: str, counts: dict, outputs: list[str] | None = None,
                 warnings: list[str] | None = None, reason: str | None = None) -> dict:
    return {"brick": name, "status": status, "counts": counts, "outputs": outputs or [],
            "warnings": (warnings or [])[:20], "observations": [], "reason": reason}


def _out(args, result: dict, brick: dict) -> None:
    if getattr(args, "as_brick", None):
        print(json.dumps({**brick, "brick": args.as_brick}, ensure_ascii=False, default=str))
    else:
        print(json.dumps(result, indent=2, ensure_ascii=False, default=str))


# ---------------------------------------------------------------- build


def attention_defs() -> list[dict]:
    f = schema_file("attention.yaml")
    return _yaml().safe_load(f.read_text(encoding="utf-8")) or [] if f.is_file() else []


def cmd_build(args) -> int:
    rows, errors, warnings, src_hash = collect()
    dec_keys = [r[0] for r in rows["decisions"]]
    for d in sorted({x for x in dec_keys if dec_keys.count(x) > 1}):
        errors.append(f"duplicate decision id {d}")
    for table, label in (("proposals", "proposal"), ("raw_items", "raw item"), ("people", "person")):
        ids = [r[0] for r in rows[table]]
        for d in sorted({x for x in ids if ids.count(x) > 1}):
            where = ", ".join(r[-1] for r in rows[table] if r[0] == d) if table == "proposals" else ""
            errors.append(f"duplicate {label} id {d}" + (f" ({where})" if where else ""))
    seen_pk = set()
    for e in rows["entries"]:
        pk = (e["key"], e["date"], e["line"])
        if pk in seen_pk:
            errors.append(f"{e['path']}:{e['line']}: duplicate entry")
        seen_pk.add(pk)
    counts = {k: len(v) for k, v in rows.items() if k != "fts"}
    if errors:
        result = {"status": "error", "errors": errors[:200], "error_count": len(errors), "warnings": warnings}
        if args.as_brick:
            _out(args, result, brick_return("", "failed", {"errors": len(errors)}, warnings=errors,
                                            reason="kb build validation failed; nothing written"))
            return 1
        print(json.dumps(result, indent=2), file=sys.stderr)
        return 1
    if args.check:
        _out(args, {"status": "valid", "counts": counts, "warnings": warnings},
             brick_return("", "success", counts, warnings=warnings))
        return 0
    sql = schema_file("kb.sql").read_text(encoding="utf-8")
    sv = re.search(r"user_version\s*=\s*(\d+)", sql).group(1)
    build_hash = hashlib.sha256((src_hash + sql + json.dumps(attention_defs(), sort_keys=True, default=str)).encode()).hexdigest()
    db = kbpath("db")
    if db.is_file() and not args.force:
        try:
            con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
            old = con.execute("select value from _build where key='source_hash'").fetchone()
            con.close()
            if old and old[0] == build_hash:
                _out(args, {"status": "unchanged", "source_hash": build_hash[:12], "warnings": warnings},
                     brick_return("", "success", {"unchanged": 1}, [rel(db)], warnings))
                return 0
        except sqlite3.Error:
            pass
    db.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=db.parent, prefix=".kb-build-", suffix=".db")
    os.close(fd)
    try:
        con = sqlite3.connect(tmp)
        con.executescript(sql)

        def ins(table: str, data: list) -> None:
            if data:
                con.executemany(f"insert into {table} values ({','.join('?' * len(data[0]))})", data)

        ins("entities", sorted(rows["entities"], key=lambda r: r[0]))
        ins("people", sorted(rows["people"], key=lambda r: r[0]))
        ins("raw_items", sorted(rows["raw_items"], key=lambda r: r[0]))
        ins("project_members", sorted(rows["project_members"], key=lambda r: (r[0], str(r[1]))))
        ins("meeting_attendees", sorted(rows["meeting_attendees"], key=lambda r: tuple(map(str, r))))
        cols = ["key", "project", "facet", "id", "date", "state", "by", "trust", "source", "owner", "due", "rag",
                "body", "path", "line"]
        ins("entries", [tuple(e[c] for c in cols) for e in sorted(rows["entries"], key=lambda e: (e["path"], e["line"]))])
        ins("decisions", sorted(rows["decisions"], key=lambda r: r[0]))
        ins("links", sorted(rows["links"], key=lambda r: tuple(map(str, r))))
        ins("sessions", sorted(rows["sessions"], key=lambda r: str(r[0])))
        ins("proposals", sorted(rows["proposals"], key=lambda r: r[0]))
        ins("fts", sorted(rows["fts"], key=lambda r: (str(r[0]), str(r[1]))))
        for q in attention_defs():
            con.execute("insert into attention_queries values (?,?,?)", (q["name"], q["sql"], q.get("description")))
        con.executemany("insert into _build values (?,?)", [("schema_version", sv), ("source_hash", build_hash)])
        con.commit()
        con.close()
        os.replace(tmp, db)
    except sqlite3.Error as exc:
        raise SystemExit(f"kb build failed while writing the index: {exc}")
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    _out(args, {"status": "built", "source_hash": build_hash[:12], "counts": counts, "warnings": warnings},
         brick_return("", "success", counts, [rel(db)], warnings))
    return 0


