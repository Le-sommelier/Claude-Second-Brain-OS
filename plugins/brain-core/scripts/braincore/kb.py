def render_state_block(con: sqlite3.Connection, slug: str) -> str:
    def q(sql, *a):
        return con.execute(sql, a).fetchall()
    st = q("select id, date, state, rag, body from entries where project=? and facet='status' order by date desc, line desc", slug)
    risks = q("select id, substr(body,1,90) b, due from current_entries where project=? and id like 'RSK-%' "
              "and state in ('open','at-risk') order by date desc, id desc", slug)
    deps = q("select count(*) from current_entries where project=? and id like 'DEP-%' and state in ('open','at-risk')", slug)[0][0]
    ms = q("select id, state, due from current_entries where project=? and id like 'MS-%' and state not in ('done','closed') "
           "order by due is null, due limit 6", slug)
    dec = q("select id, title from decisions where project=? and status='proposed' order by date", slug)
    last = q("select max(d) from (select max(date) d from entries where project=? union all "
             "select max(date) from decisions where project=?)", slug, slug)[0][0]
    lines = [GEN_START, "## Current state", ""]
    if st:
        rag_rows = [r for r in st if r[3]]
        if rag_rows:
            cur, since = rag_rows[0], rag_rows[0][1]
            for r in rag_rows[1:]:
                if r[3] != cur[3]:
                    break
                since = r[1]
            lines.append(f"- **RAG**: {cur[3]} " + (f"since {since}" if since != cur[1]
                         else f"as of {cur[1]} (no earlier RAG on record)") + f" (entry `{cur[0]}`)")
        else:
            lines.append("- **RAG**: none recorded")
        first = st[0][4].splitlines()[0][:200] if st[0][4] else ""
        lines.append(f"- **Latest status** (`{st[0][0]}`, {st[0][1]}): {st[0][2]}. {first}".rstrip())
    else:
        lines.append("- **Status**: no entries yet")
    lines.append(f"- **Open risks** (RSK): {len(risks)}; open dependencies/blockers (DEP): {deps}"
                 + "".join(f"\n  - {r[0]}: {r[1]}" + (f" (due {r[2]})" if r[2] else "") for r in risks[:5]))
    lines.append("- **Next milestones**: " + ("; ".join(f"{m[0]} ({m[1]}" + (f", {m[2]}" if m[2] else ", undated") + ")"
                                                      for m in ms) or "none"))
    lines.append("- **Decisions awaiting confirmation**: " + (f"{len(dec)}: " + "; ".join(d[0] for d in dec[:8])
                                                              + (" ..." if len(dec) > 8 else "") if dec else "none"))
    lines.append(f"- **Last activity**: {last or 'never'}")
    lines += ["", GEN_END]
    return "\n".join(lines)


def refresh_readme(readme: Path, block: str) -> bool:
    text = readme.read_text(encoding="utf-8")
    if GEN_START in text and GEN_END in text:
        new = re.sub(re.escape(GEN_START) + r".*?" + re.escape(GEN_END), lambda m: block, text, count=1, flags=re.DOTALL)
    else:
        m = FM_RE.match(text)
        head = text[:m.end()] if m else ""
        new = head + ("\n" if head else "") + block + "\n\n" + text[len(head):].lstrip("\n")
    if new != text:
        readme.write_text(new, encoding="utf-8")
        return True
    return False


def cmd_index(args) -> int:
    changed = 0
    keys = ("raw", "projects", "people", "topics", "digests", "inbox", "system")
    code = kbpath("code").resolve()
    for key in keys:
        base = kbpath(key)
        if not base.is_dir():
            continue
        for d in sorted((x for x in base.rglob("*") if x.is_dir()), reverse=True) + [base]:
            relparts = d.relative_to(base).parts
            if any(x.startswith(".") or x in SKIP_DIRS for x in relparts) or code in d.resolve().parents \
                    or d.resolve() == code:
                continue
            if key == "system" and relparts[:1] and relparts[0] in INDEX_SKIP_SYSTEM:
                continue
            subdirs = sorted(x for x in d.iterdir() if x.is_dir() and not x.name.startswith((".", "_"))
                             and x.name not in SKIP_DIRS and not (key == "system" and d == base and x.name in INDEX_SKIP_SYSTEM))
            files = sorted(x for x in d.iterdir() if x.is_file() and not x.name.startswith((".", "_"))
                           and x.suffix in {".md", ".txt", ".yaml", ".jsonl", ".sql"} and x.name != "CLAUDE.md")
            if not subdirs and not files:
                continue
            out = [INDEX_MARK, f"# {d.name}", ""]
            if subdirs:
                out += ["## Folders", ""] + [f"- [{x.name}/]({x.name}/_index.md)" if (x / "_index.md").exists()
                                             else f"- {x.name}/" for x in subdirs] + [""]
            if files:
                out += ["## Files", ""]
                for x in files:
                    t = folder_title(x) if x.suffix == ".md" else x.stem
                    out.append(f"- [{x.name}]({x.name.replace(' ', '%20')})" + (f": {t}" if t != x.stem else ""))
                out.append("")
            new = "\n".join(out)
            idx = d / "_index.md"
            if not idx.exists() or idx.read_text(encoding="utf-8") != new:
                idx.write_text(new, encoding="utf-8")
                changed += 1
    refreshed = 0
    if kbpath("db").is_file():
        con = open_ro()
        pdir = kbpath("projects")
        for d in sorted(x for x in pdir.iterdir() if x.is_dir() and not x.name.startswith((".", "_"))) if pdir.is_dir() else []:
            if (d / "README.md").is_file() and refresh_readme(d / "README.md", render_state_block(con, d.name)):
                refreshed += 1
    counts = {"index_files_written": changed, "readmes_refreshed": refreshed}
    _out(args, {"status": "success", **counts}, brick_return("", "success", counts))
    return 0


