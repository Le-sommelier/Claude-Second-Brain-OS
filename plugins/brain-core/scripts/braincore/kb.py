    i.add_argument("--as-brick", metavar="NAME")
    i.set_defaults(fn=cmd_index)
    q = ks.add_parser("query", help="read-only SQL, JSON lines out")
    q.add_argument("sql")
    q.set_defaults(fn=cmd_query)
    s = ks.add_parser("show", help="everything known about an ID")
    s.add_argument("id")
    s.set_defaults(fn=cmd_show)
