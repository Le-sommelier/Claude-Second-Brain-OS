def trust_for(con: sqlite3.Connection, project: str, raw_id: str) -> tuple[str, str]:
    """Deterministic trust tier of a raw item for a project. Returns (tier, reason).

    HIGH: the owner, the project owner or a decision-maker attended. MEDIUM: a project team member
    attended, or the item is Slack/Confluence. LOW: otherwise. Only `attended` counts."""
    if raw_id.startswith(("slack-", "conf-")):
        return "medium", "Slack/Confluence source (same rule as `kb append`)"
    present = {r[0] for r in con.execute(
        "select person from meeting_attendees where raw_id = ? and attendance = 'attended'", (raw_id,))}
    att_self = con.execute("select attendance from raw_items where id = ?", (raw_id,)).fetchone()
    if owner_id() in present or (att_self and att_self[0] == "attended"):
        return "high", "the owner attended"
    members = {r["person"]: r for r in con.execute(
        "select person, is_owner, is_decision_maker from project_members where project = ?", (f"proj-{project}",))}
    lead = sorted(p for p in present if p in members and (members[p]["is_owner"] or members[p]["is_decision_maker"]))
    if lead:
        return "high", f"owner/decision-maker attended: {', '.join(lead)}"
    team = sorted(p for p in present if p in members)
    if team:
        return "medium", f"team member attended: {', '.join(team)}"
    return "low", "no project member attended"


