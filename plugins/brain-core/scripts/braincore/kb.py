HEDGE_RE = re.compile(r"not formally ratified|recommendation|idea for comment|pending|not final|proposed", re.I)
_RAW_CACHE: dict[str, dict] = {}


def raw_meta(raw_id: str) -> dict | None:
    """Frontmatter of a raw item by ID (attendance, sensitivity), read from raw/ on demand."""
    if not _RAW_CACHE:
        base = kbpath("raw")
        if base.is_dir():
            for p in list(base.rglob("*.summary.md")) + list(base.rglob("*.meta.yaml")) + list(base.rglob("*.md")):
                if p.name.startswith("_"):
                    continue
                m = re.match(r"^(.*?)(\.summary\.md|\.meta\.yaml|\.md)$", p.name)
                rid = m.group(1) if m else p.stem
                try:
                    if p.suffix == ".yaml":
                        fm = _yaml().safe_load(p.read_text(encoding="utf-8")) or {}
                    else:
                        fm, _ = split_fm(p.read_text(encoding="utf-8"))
                except Exception:
                    continue
                if isinstance(fm, dict):
                    _RAW_CACHE.setdefault(str(fm.get("id") or rid), {}).update(fm)
    return _RAW_CACHE.get(raw_id)


def source_confidential(sid: str) -> bool:
    meta = raw_meta(sid) or {}
    if meta.get("redact_content") or str(meta.get("sensitivity", "")).lower() == "confidential":
        return True
    m = re.match(r"^slack-\d{4}-\d{2}-\d{2}-(.+)$", sid)
    return bool(m and is_confidential_channel(m.group(1)))


def roster_of(project: str) -> list[dict]:
    teams = kbpath("projects") / project / "teams.md"
    if not teams.is_file():
        return []
    fm, _ = split_fm(teams.read_text(encoding="utf-8"))
    return fm.get("members") or []


def source_trust(sid: str, roster: list[dict]) -> str:
    if sid.startswith(("slack-", "conf-")):
        return "medium"
    if sid in ("owner", owner_id()):
        return "low"  # direct input is not evidence an AI may auto-confirm on; the owner writes by: human
    meta = raw_meta(sid) if sid.startswith(("mtg-", "note-")) else None
    att = (meta or {}).get("attendance")
    if sid.startswith("note-") and meta is not None:
        return "high"  # the owner's own notes
    if not isinstance(att, dict):
        return "high" if att == "attended" else "low"
    present = {p for p, a in att.items() if a == "attended"}
    lead = {m.get("person") for m in roster if m.get("owner") or m.get("decision_maker")}
    team = {m.get("person") for m in roster}
    if owner_id() in present or present & lead:
        return "high"
    return "medium" if present & team else "low"


def next_number(p: Path, prefix: str) -> int:
    if not p.is_file():
        return 1
    nums = [int(m.group(1)) for m in re.finditer(rf"^## \d{{4}}-\d{{2}}-\d{{2}} · {prefix}-(\d{{3}}) ·",
                                                  blank_fences(p.read_text(encoding="utf-8")), re.M)]
    return max(nums, default=0) + 1


def entry_text(d: str, eid: str, state: str, trust: str, sources: list[str], body: str, by: str = "ai", **extra) -> str:
    parts = [f"by: {by}"] + ([] if by == "human" else [f"trust: {trust}"]) + ["source: " + ", ".join(sources)]
    parts += [f"{k}: {v}" for k, v in extra.items() if v]
    if any(source_confidential(s) for s in sources):
        parts.append("sensitivity: confidential")
    return f"## {d} · {eid} · {state}\n{' · '.join(parts)}\n{body.strip()}\n"


PREFIX_FACET = {"STA": "status", "RSK": "risks", "DEP": "risks", "MS": "milestones", "RES": "resources", "HYP": "hypotheses"}


def normalise_payload(payload, project: str) -> list[dict]:
    """Accept both payload shapes and return the internal list form.

    Module shape: {"project": slug, "entries": [{"id_prefix": "RSK|DEP|MS|STA|RES|HYP|DEC",
    "facet"?, "status", "by"?, "source", "owner"?, "due"?, "rag"?, "title"?, "id"?, "date"?, "body"}]}.
    Legacy shape: a list of {"facet", "prefix", "state", "date", ...} or {"type": "decision", ...}.
    `trust` in a payload is ignored: it is always computed from the sources."""
    if isinstance(payload, dict):
        if payload.get("project") and payload["project"] != project:
            raise SystemExit(f"payload is for project {payload['project']!r}, not {project!r}")
        payload = payload.get("entries")
    if not isinstance(payload, list):
        raise SystemExit('payload must be {"project", "entries": [...]} or a JSON array')
    out = []
    for it in payload:
        if not isinstance(it, dict):
            out.append(it)
            continue
        it = dict(it)
        px = it.pop("id_prefix", None)
        if px == "DEC":
            it["type"] = "decision"
            if not it.get("title"):
                it["title"] = str(it.get("body", "")).strip().splitlines()[0][:80] if it.get("body") else ""
        elif px:
            it.setdefault("prefix", px)
            it.setdefault("facet", PREFIX_FACET.get(px))
        if "state" not in it and "status" in it and it.get("type") != "decision":
            it["state"] = it.pop("status")
        it.setdefault("date", date.today().isoformat())
        out.append(it)
    return out


def cmd_append(args) -> int:
    yaml = _yaml()
    pfile = Path(args.file) if Path(args.file).is_absolute() else root() / args.file
    payload = normalise_payload(json.loads(pfile.read_text(encoding="utf-8")), args.project)
    proj = kbpath("projects") / args.project
    if not proj.is_dir():
        raise SystemExit(f"no such project {args.project} (create it with `brain new project {args.project}`)")
    roster = roster_of(args.project)
    plan: list[tuple[Path, str]] = []
    errors: list[str] = []
    pending_nums: dict[tuple[str, str], int] = {}
    assigned: list[dict] = []
    for i, it in enumerate(payload):
        where = f"payload[{i}]"
        if not isinstance(it, dict):
            errors.append(f"{where}: must be an object")
            continue
        sources = it.get("source") or []
        if isinstance(sources, str):
            sources = [s.strip() for s in sources.split(",") if s.strip()]
        if not sources:
            errors.append(f"{where}: source is mandatory")
            continue
        trust = max((source_trust(s, roster) for s in sources), key=lambda t: TRUST_RANK[t])
        d = str(it.get("date", ""))
        if not DATE_RE.match(d):
            errors.append(f"{where}: bad date {d!r}")
            continue
        if it.get("type") == "decision":
            body = str(it.get("body", "")).strip()
            if not it.get("title") or not body:
                errors.append(f"{where}: decision needs title and body")
                continue
            ddir = proj / "decisions"
            existing = [int(m.group(1)) for f in (ddir.glob("*.md") if ddir.is_dir() else [])
                        for m in [re.search(r"id: DEC-" + re.escape(args.project) + r"-(\d+)", f.read_text(encoding="utf-8"))] if m]
            key = ("decision", "")
            pending_nums[key] = pending_nums.get(key, max(existing, default=0)) + 1
            did = f"DEC-{args.project}-{pending_nums[key]:03d}"
            if it.get("by") == "human":
                fm = {"id": did, "date": d, "status": "accepted", "by": "human", "title": it["title"],
                      "source": ", ".join(sources)}
            else:
                auto = trust == "high" and not HEDGE_RE.search(body + str(it["title"])) and not args.no_auto_confirm
                fm = {"id": did, "date": d, "status": "accepted" if auto else "proposed", "by": "ai-confirmed" if auto else "ai",
                      "title": it["title"], "source": ", ".join(sources), "origin": "ingest", "trust": trust}
            if it.get("owner"):
                fm["owner"] = it["owner"]
            if any(source_confidential(s) for s in sources):
                fm["sensitivity"] = "confidential"
            slug = re.sub(r"[^a-z0-9]+", "-", str(it["title"]).lower()).strip("-")[:60].strip("-")
            assigned.append({"id": did, "key": did, "file": rel(ddir / f"{d}-{slug}.md"), "status": fm["status"], "new": True})
            plan.append((ddir / f"{d}-{slug}.md", "---\n" + yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=200)
                         + f"---\n\n# {it['title']}\n\n{body}\n"))
            continue
        facet, prefix = it.get("facet"), it.get("prefix")
        allowed = FACETS.get(facet)
        allowed = (allowed,) if isinstance(allowed, str) else allowed
        if not allowed or prefix not in allowed:
            errors.append(f"{where}: facet/prefix mismatch ({facet}/{prefix})")
            continue
        if it.get("state") not in STATES:
            errors.append(f"{where}: bad state {it.get('state')!r}")
            continue
        target = proj / f"{facet}.md"
        if not target.is_file():
            errors.append(f"{where}: {target.name} does not exist (append never creates facet files)")
            continue
        if it.get("id"):
            eid = it["id"]
            if not re.match(rf"^{prefix}-\d{{3}}$", eid) or f" · {eid} · " not in target.read_text(encoding="utf-8"):
                errors.append(f"{where}: unknown ID {eid}")
                continue
        else:
            key = (facet, prefix)
            pending_nums[key] = pending_nums.get(key, next_number(target, prefix) - 1) + 1
            eid = f"{prefix}-{pending_nums[key]:03d}"
        by = it.get("by") or "ai"
        if by not in ("ai", "human"):
            errors.append(f"{where}: by must be ai or human (ai-confirmed comes from `brain kb confirm`)")
            continue
        plan.append((target, entry_text(d, eid, it["state"], trust, sources, str(it.get("body", "")), by=by,
                                        owner=it.get("owner"), due=it.get("due"), rag=it.get("rag"),
                                        refs=",".join(it["refs"]) if isinstance(it.get("refs"), list) else it.get("refs"))))
        assigned.append({"id": eid, "key": f"{args.project}/{eid}", "file": rel(target), "new": not it.get("id")})
    if errors:
        print(json.dumps({"status": "error", "errors": errors}, indent=1), file=sys.stderr)
        return 1
    written = []
    if not args.dry_run:
        for target, text in plan:
            if target.parent.name == "decisions":
                target.parent.mkdir(parents=True, exist_ok=True)
                n = 2
                while target.exists():
                    target = target.with_name(re.sub(r"(-\d+)?$", f"-{n}", target.stem, count=1) + ".md")
                    n += 1
                target.write_text(text, encoding="utf-8")
            else:
                with target.open("a", encoding="utf-8") as fh:
                    fh.write("\n" + text)
            written.append(rel(target))
    print(json.dumps({"status": "success", "dry_run": args.dry_run, "appended": len(plan), "ids": assigned,
                      "files": sorted(set(written) or {rel(p) for p, _ in plan})}))
    return 0


