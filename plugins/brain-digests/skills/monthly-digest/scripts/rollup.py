#!/usr/bin/env python3
"""Deterministic monthly rollups from the project logs.

    python3 ${CLAUDE_SKILL_DIR}/scripts/rollup.py [--month YYYY-MM] [--backfill] [--today YYYY-MM-DD] [--dry-run]

Per project with activity: projects/<slug>/rollups/YYYY-MM.md. Across projects: digests/monthly/YYYY-MM.md.
Default window = previous and current month. No model: it lists what was logged, with IDs.
Only files carrying the generated marker are replaced; unchanged content is not rewritten.
Confidential entries and decisions are listed without their body.
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))  # plugins/<m>/skills/<s>/scripts/x.py
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "scripts"))
import kbparse  # noqa: E402
from brainos import frontmatter  # noqa: E402
from brainos.workspace import emit, path, rel  # noqa: E402

MARK = "<!-- generated by brain rollup; do not edit -->"
HIDDEN = "(confidential, see source)"


def month_bounds(label: str) -> tuple[str, str]:
    y, m = map(int, label.split("-"))
    first = date(y, m, 1)
    nxt = date(y + (m == 12), (m % 12) + 1, 1)
    return first.isoformat(), (nxt - timedelta(days=1)).isoformat()


def short(s: str | None, n: int = 130) -> str:
    return " ".join((s or "").split())[:n]


def title_of(pdir: Path) -> str:
    readme = pdir / "README.md"
    if readme.is_file():
        fm = frontmatter.read(readme)
        if fm.get("title"):
            return str(fm["title"])
        m = re.search(r"^# (.+)$", readme.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1).strip()
    return pdir.name


def load_decisions(pdir: Path) -> list[dict]:
    out = []
    ddir = pdir / "decisions"
    for f in sorted(ddir.glob("*.md")) if ddir.is_dir() else []:
        fm = frontmatter.read(f)
        if fm.get("date"):
            out.append({"id": fm.get("id", f.stem), "date": str(fm["date"]), "status": fm.get("status", "proposed"),
                        "by": fm.get("by", "ai"), "trust": fm.get("trust"), "title": fm.get("title"),
                        "confidential": fm.get("sensitivity") == "confidential"})
    return sorted(out, key=lambda d: (d["date"], d["id"]))


def block(entries: list[dict], decisions: list[dict]) -> list[str]:
    out: list[str] = []
    if entries:
        counts: dict[str, int] = {}
        for e in entries:
            counts[e["facet"]] = counts.get(e["facet"], 0) + 1
        out.append("Logged: " + ", ".join(f"{n} {f}" for f, n in sorted(counts.items())) + ".")
        for e in entries:
            conf = e["meta"].get("sensitivity") == "confidential"
            rag = f" / {e['meta']['rag']}" if e["meta"].get("rag") else ""
            out.append(f"- `{e['id']}` {e['date']} {e['state']}{rag}: {HIDDEN if conf else short(e['body'])}")
    if decisions:
        acc = sum(1 for d in decisions if d["status"] == "accepted")
        prop = sum(1 for d in decisions if d["status"] == "proposed")
        out.append(f"Decisions: {len(decisions)} ({acc} accepted, {prop} proposed).")
        for d in decisions:
            out.append(f"- `{d['id']}` {d['date']} {d['status']} ({d['by']}, trust {d['trust'] or '-'}): "
                       f"{HIDDEN if d['confidential'] else short(d['title'])}")
    return out


def write(p: Path, text: str, dry: bool, stats: dict) -> None:
    if p.is_file():
        old = p.read_text(encoding="utf-8")
        if MARK not in old:
            stats["skipped_handwritten"] += 1
            return
        if old == text:
            stats["unchanged"] += 1
            return
    stats["written"] += 1
    if not dry:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--month", help="one month, YYYY-MM")
    ap.add_argument("--backfill", action="store_true", help="every month that has data")
    ap.add_argument("--today")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    base = path("core", "projects")
    dirs = sorted(p for p in base.iterdir() if p.is_dir() and not p.name.startswith(("_", "."))) if base.is_dir() else []
    data = {d.name: (d, kbparse.project_entries(d), load_decisions(d)) for d in dirs}

    today = date.fromisoformat(args.today) if args.today else date.today()
    if args.month:
        months = [args.month]
    elif args.backfill:
        dates = [x["date"][:7] for _, es, ds in data.values() for x in [*es, *ds]]
        months = sorted(set(dates))
    else:
        prev = (today.replace(day=1) - timedelta(days=1))
        months = [f"{prev.year}-{prev.month:02d}", f"{today.year}-{today.month:02d}"]

    stats = {"written": 0, "unchanged": 0, "skipped_handwritten": 0}
    outputs: list[str] = []
    digests = path("core", "digests") / "monthly"
    for m in months:
        lo, hi = month_bounds(m)
        lines: list[str] = []
        for slug, (d, entries, decisions) in data.items():
            es = sorted((e for e in entries if lo <= e["date"] <= hi), key=lambda e: (e["date"], e["facet"], e["id"], e["line"]))
            ds = [x for x in decisions if lo <= x["date"] <= hi]
            body = block(es, ds)
            if not body:
                continue
            sources = {s.strip() for e in es for s in e["meta"].get("source", "").split(",")} - {""}
            title = title_of(d)
            text = (f"---\ntype: rollup\nproject: {slug}\nperiod: {m}\nby: ai\n---\n\n# {title}: {m}\n\n{MARK}\n\n"
                    + "\n".join(body) + f"\n\nSources cited: {len(sources)} distinct.\n")
            p = d / "rollups" / f"{m}.md"
            write(p, text, args.dry_run, stats)
            outputs.append(rel(p))
            lines.append(f"- **{title}** ([[{slug}/rollups/{m}]]): {body[0] if body[0].startswith('Logged') else 'decisions only'}")
        if lines:
            text = f"---\ntype: digest\nperiod: {m}\nby: ai\n---\n\n# Monthly digest {m}\n\n{MARK}\n\n" + "\n".join(lines) + "\n"
            p = digests / f"{m}.md"
            write(p, text, args.dry_run, stats)
            outputs.append(rel(p))

    emit({"brick": "monthly-rollup", "status": "success", "dry_run": args.dry_run, "months": months,
          "counts": stats, "outputs": outputs, "warnings": [], "observations": [], "reason": None})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
