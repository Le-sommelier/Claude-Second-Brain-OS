#!/usr/bin/env python3
"""Assemble the briefing a grilling session leans on: one project's facet logs, decisions, people and recent meetings.

    python3 gather_context.py --project <slug> [--out PATH]

Read-only. Runs `brain kb query` (the index over the markdown) a handful of times and writes one markdown
briefing to <grill.context_dir>/<slug>-context.md. Entries whose file is confidential, and meetings flagged
redact_content, are left out entirely. Bodies are clipped to 400 characters: the briefing is for orientation,
and the session reads full entries with `brain kb show <id>` when a question needs the detail.
Exits non-zero, writing nothing, when `brain` is missing or the project has no rows.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))
from brainos.confidential import is_confidential_path  # noqa: E402
from brainos.workspace import emit, path, rel, root  # noqa: E402

SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
BODY_MAX = 400

QUERIES = {
    "entries": ("select id, facet, state, by, trust, rag, due, date, path, substr(body,1,{n}) as body "
                "from current_entries where project='{p}' order by facet, id"),
    "decisions": ("select id, title, status, by, trust, date, owner, path from decisions "
                  "where project='{p}' order by date"),
    "members": ("select pe.id as person, pe.name, pe.role, m.role as project_role, m.is_owner, m.is_decision_maker "
                "from project_members m join people pe on pe.id = m.person where m.project='{p}' order by pe.name"),
    "meetings": ("select id, date, title, meeting_type, path, redact_content from raw_items "
                 "where project='{p}' and kind='mtg' order by date desc limit 8"),
}


def kb_query(sql: str) -> list[dict]:
    exe = shutil.which("brain")
    if not exe:
        raise RuntimeError("`brain` is not on PATH: run /brain-core:setup, or open the workspace in Claude Code with brain-core enabled")
    res = subprocess.run([exe, "kb", "query", sql], capture_output=True, text=True, cwd=root(), timeout=60)
    if res.returncode != 0:
        raise RuntimeError(f"brain kb query failed: {(res.stderr or res.stdout).strip()[:300]}")
    rows = []
    for line in res.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            rows.append(json.loads(line))
    return rows


def visible(row: dict) -> bool:
    return not is_confidential_path(row.get("path") or "") and not row.get("redact_content")


def render(slug: str, data: dict[str, list[dict]]) -> str:
    L = [f"# Grill briefing: {slug}", "",
         "_Generated by `gather_context.py` from the knowledge-base index. Read-only orientation; use "
         "`brain kb show <id>` for full entries._", ""]
    L += ["## People", ""]
    L += [f"- {m['name']} ({m['person']}), {m.get('role') or 'role unknown'}; on this project: "
          f"{m.get('project_role') or 'member'}{', owner' if m.get('is_owner') else ''}"
          f"{', decision maker' if m.get('is_decision_maker') else ''}" for m in data["members"]] or ["_No members recorded._"]
    L += ["", "## Decisions", ""]
    L += [f"- {d['id']} [{d['status']}, by {d['by']}, trust {d.get('trust') or '-'}] {d.get('title') or ''} ({d['date']}, "
          f"owner {d.get('owner') or '-'})" for d in data["decisions"]] or ["_No decisions recorded._"]
    by_facet: dict[str, list[dict]] = {}
    for e in data["entries"]:
        by_facet.setdefault(e["facet"], []).append(e)
    for facet in ("status", "risks", "hypotheses", "milestones", "resources", "teams"):
        rows = by_facet.pop(facet, [])
        L += ["", f"## {facet.capitalize()} (current state per entry)", ""]
        for e in rows:
            meta = ", ".join(x for x in (e["state"], f"rag {e['rag']}" if e.get("rag") else "",
                                         f"due {e['due']}" if e.get("due") else "", f"by {e['by']}",
                                         f"trust {e['trust']}" if e.get("trust") else "") if x)
            L.append(f"- **{e['id']}** ({e['date']}; {meta}): {' '.join((e.get('body') or '').split())}")
        if not rows:
            L.append("_None._")
    for facet, rows in sorted(by_facet.items()):
        L += ["", f"## {facet.capitalize()}", ""]
        L += [f"- **{e['id']}** ({e['date']}; {e['state']}): {' '.join((e.get('body') or '').split())}" for e in rows]
    L += ["", "## Recent meetings", ""]
    L += [f"- {m['date']} {m.get('title') or m['id']} ({m['id']})" for m in data["meetings"]] or ["_None indexed._"]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--project", required=True)
    ap.add_argument("--out")
    args = ap.parse_args()
    if not SLUG_RE.match(args.project):
        emit({"brick": "grill-context", "status": "failed", "reason": f"project slug {args.project!r} must match [a-z0-9-]+"})
        return 1
    proj = path("core", "projects") / args.project
    if not proj.is_dir():
        emit({"brick": "grill-context", "status": "failed", "reason": f"no project folder {rel(proj)}"})
        return 1
    if is_confidential_path(rel(proj) + "/README.md"):
        emit({"brick": "grill-context", "status": "failed", "reason": "project is confidential: grill it from the owner's own words, not from the index"})
        return 1
    try:
        data = {k: [r for r in kb_query(q.format(p=args.project, n=BODY_MAX)) if visible(r)] for k, q in QUERIES.items()}
    except (RuntimeError, subprocess.TimeoutExpired, ValueError) as exc:
        emit({"brick": "grill-context", "status": "failed", "reason": str(exc)})
        return 1
    if not any(data.values()):
        emit({"brick": "grill-context", "status": "failed", "reason": f"the index has no rows for {args.project}: run `brain kb build`"})
        return 1
    out = Path(args.out) if args.out else path("grill", "context_dir") / f"{args.project}-context.md"
    out = out if out.is_absolute() else root() / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(args.project, data), encoding="utf-8")
    emit({"brick": "grill-context", "status": "success",
          "counts": {k: len(v) for k, v in data.items()}, "outputs": [rel(out)], "warnings": [], "observations": []})
    return 0


if __name__ == "__main__":
    sys.exit(main())
